from __future__ import annotations

from .config import AGREEMENT, CLASSES, PRIMARY_AGREEMENT
from .figures import NAMES


def _f(v):
    return "—" if v is None else f"{v:.3f}"


def markdown(r: dict) -> str:
    d, sel, e = r["data"], r["selected"]["model"], r["environment"]
    t = r["test"][PRIMARY_AGREEMENT]
    lines = [
        "# Results: ai4mars-terrain-segmentation", "",
        f"Generated by `python -m terrain_seg.train` at {r['generated_utc']} (Python {e['python']}, PyTorch {e['torch']}, "
        f"torchvision {e['torchvision']}, ImageNet backbone: {e['pretrained_backbone']}).", "",
        "## Data", "",
        f"- Training labels (crowd): {d['n_train']:,} images from {d['train_positions']:,} rover positions; validation "
        f"{d['n_validation']:,} images from {d['validation_positions']:,} other positions ({d['n_validation_scored']:,} scored each epoch).",
        f"- Test (expert labels): {d['n_test']} images; {d['test_images_at_unseen_positions']} of them are at rover positions with no training image.",
        "- Training pixel share: " + ", ".join(f"{c} {v:.1%}" for c, v in d["train_pixel_share"].items())
        + "; loss weights " + ", ".join(f"{c} {v:.2f}" for c, v in d["class_weights"].items()) + ".", "",
        "## Model search (validation mIoU, crowd labels)", "",
        "| Model | Validation mIoU | Epochs run | Minutes |", "|---|---|---|---|",
    ]
    for m, v in r["validation_miou"].items():
        h = r["histories"].get(m, [])
        lines.append(f"| {NAMES[m]} | {v:.3f} | {len(h) or '—'} | {sum(x['seconds'] for x in h) / 60:.0f} |" if h
                     else f"| {NAMES[m]} | {v:.3f} | — | — |")
    lines += ["", f"Selected: **{NAMES[sel]}**.", "",
              "## Test (expert labels, scored once at full resolution)", "",
              "| Model | " + " | ".join(f"mIoU {a}" for a in AGREEMENT) + f" | Pixel acc. {PRIMARY_AGREEMENT} |",
              "|---|" + "---|" * (len(AGREEMENT) + 1)]
    for m in t:
        lines.append(f"| {NAMES[m]} | " + " | ".join(f"{r['test'][a][m]['miou']:.3f}" for a in AGREEMENT)
                     + f" | {t[m]['pixel_accuracy']:.3f} |")
    iv = r["test_intervals_primary"]
    lines += ["", f"95% bootstrap intervals over test images ({r['config']['n_bootstrap']} resamples, {PRIMARY_AGREEMENT}):", ""]
    lines += [f"- {NAMES[m]}: {a:.3f}–{b:.3f}" for m, (a, b) in iv["miou_ci95"].items()]
    lines += ["", f"Paired mIoU difference, {NAMES[sel]} minus each other model:", ""]
    lines += [f"- vs {NAMES[m]}: {v['mean']:+.3f} ({v['ci95'][0]:+.3f} to {v['ci95'][1]:+.3f})" for m, v in iv["miou_difference_vs"].items()]
    lines += ["", f"## Per class (test, {PRIMARY_AGREEMENT})", "", "| Model | " + " | ".join(f"IoU {c}" for c in CLASSES) + " |",
              "|---|" + "---|" * len(CLASSES)]
    lines += [f"| {NAMES[m]} | " + " | ".join(_f(t[m]["iou"][c]) for c in CLASSES) + " |" for m in t]
    lines += ["", "Labelled test pixels: " + ", ".join(f"{c} {n:,}" for c, n in t[sel]["pixels"].items()) + ".", ""]
    u = r["test_unseen_positions_primary"]
    if u:
        lines += [f"## Test images at rover positions never seen in training ({d['test_images_at_unseen_positions']} images)", "",
                  "| Model | mIoU | Pixel acc. |", "|---|---|---|"]
        lines += [f"| {NAMES[m]} | {s['miou']:.3f} | {s['pixel_accuracy']:.3f} |" for m, s in u.items()]
        lines.append("")
    lines += ["Figures: " + ", ".join(f"`{v}`" for v in r["figures"].values()), ""]
    return "\n".join(lines)
