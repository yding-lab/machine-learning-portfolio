from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.ticker
import numpy as np
from matplotlib.colors import ListedColormap

from .config import AGREEMENT, CLASSES, IGNORE, PRIMARY_AGREEMENT

CREDIT = ("Images: NASA/JPL-Caltech (Curiosity NAVCAM). Labels: AI4Mars v0.6, NASA JPL (Swan et al. 2021), "
          "zenodo.org/records/15995036, CC BY 4.0.")
SOURCE = "Data: AI4Mars (NASA JPL, via data.gov), Curiosity NAVCAM; test = expert labels. Generated by python -m terrain_seg.train"
COLORS = ["#c8823c", "#5b6b7d", "#e8c95a", "#b03a2e"]  # soil, bedrock, sand, big rock
NAMES = {"majority": "Majority class", "unet": "U-Net (scratch)", "lraspp_mobilenet_v3": "LR-ASPP MobileNetV3"}
BG, INK, MUTED, GRID = "#fcfcfa", "#1f1f1f", "#555555", "#e6e6e6"


def _style(ax):
    ax.set_facecolor(BG)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.tick_params(colors=MUTED)
    ax.grid(axis="x", color=GRID)
    ax.set_axisbelow(True)


def _save(fig, out: Path, name: str, note: str, root: Path) -> str:
    fig.text(0.01, -0.5 / fig.get_figheight(), note, fontsize=7.5, color=MUTED, wrap=True)
    p = out / f"{name}.png"
    fig.savefig(p, dpi=110, facecolor=BG, bbox_inches="tight")
    plt.close(fig)
    try:
        return str(p.resolve().relative_to(root))
    except ValueError:
        return str(p)


def _overlay(ax, im, lab, title):
    ax.imshow(im, cmap="gray")
    rgba = np.zeros(lab.shape + (4,))
    for k, c in enumerate(COLORS):
        rgba[lab == k] = (*matplotlib.colors.to_rgb(c), 0.5)
    ax.imshow(rgba)
    ax.set_title(title, fontsize=9, color=INK)
    ax.axis("off")


def save_figures(out: Path, r: dict, imgs, labels, preds, root: Path) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    sel = r["selected"]["model"]
    paths = {}

    # 1. examples: image, expert label, selected model's prediction (on labelled pixels)
    cm = r["confusion_primary"]
    labelled = np.array([(y != IGNORE).mean() for y in labels])
    order = np.argsort(-labelled)
    picks = [order[int(q * (len(order) - 1))] for q in (0.0, 0.25, 0.5)][:min(3, len(order))]
    fig, axes = plt.subplots(len(picks), 3, figsize=(9, 3 * len(picks)), squeeze=False)
    fig.patch.set_facecolor(BG)
    for row, i in zip(axes, picks):
        row[0].imshow(imgs[i], cmap="gray"); row[0].axis("off"); row[0].set_title("NAVCAM image", fontsize=9)
        _overlay(row[1], imgs[i], labels[i], f"expert label ({PRIMARY_AGREEMENT})")
        p = preds[sel][i].copy()
        p[labels[i] == IGNORE] = IGNORE
        _overlay(row[2], imgs[i], p, f"{NAMES[sel]} (labelled pixels)")
    handles = [matplotlib.patches.Patch(color=c, label=n) for c, n in zip(COLORS, CLASSES)]
    fig.legend(handles=handles, loc="upper center", ncol=4, frameon=False, bbox_to_anchor=(0.5, 1.02))
    paths["examples"] = _save(fig, out, "examples", CREDIT + " This figure is shared under CC BY 4.0.", root)

    # 2. per-class IoU by model (primary agreement level)
    t = r["test"][PRIMARY_AGREEMENT]
    models = list(t)
    fig, ax = plt.subplots(figsize=(8, 4.2))
    fig.patch.set_facecolor(BG)
    _style(ax)
    width = 0.8 / len(models)
    shades = ["#bdbdbd", "#8fb3e0", "#2a78d6"]
    for j, m in enumerate(models):
        vals = [t[m]["iou"][c] or 0 for c in CLASSES]
        bars = ax.bar(np.arange(K := len(CLASSES)) + (j - (len(models) - 1) / 2) * width, vals, width * 0.92,
                      color=shades[j % 3], label=NAMES[m])
        for b, v in zip(bars, vals):
            ax.text(b.get_x() + b.get_width() / 2, v + 0.01, f"{v:.2f}", ha="center", fontsize=7, color=MUTED)
    px = lambda n: f"{n / 1e6:.1f}M px" if n >= 1e6 else f"{n:,} px"
    ax.set_xticks(range(K), [f"{c}\n({px(t[sel]['pixels'][c])})" for c in CLASSES])
    ax.set_ylabel("IoU (test)")
    ax.grid(axis="y", color=GRID); ax.grid(axis="x", visible=False)
    ax.set_ylim(0, 1)
    ax.legend(frameon=False, fontsize=8)
    ax.set_title(f"Per-class IoU on the expert test labels ({PRIMARY_AGREEMENT})", loc="left", color=INK)
    paths["per_class_iou"] = _save(fig, out, "per_class_iou", SOURCE, root)

    # 3. confusion matrix of the selected model (share of each true class)
    c = np.array(cm[sel], dtype=float)
    c = c / np.maximum(c.sum(1, keepdims=True), 1)
    fig, ax = plt.subplots(figsize=(5, 4.4))
    fig.patch.set_facecolor(BG)
    ax.imshow(c, cmap="Blues", vmin=0, vmax=1)
    for a in range(K):
        for b in range(K):
            ax.text(b, a, f"{c[a, b]:.2f}", ha="center", va="center", fontsize=9, color="white" if c[a, b] > 0.5 else INK)
    ax.set_xticks(range(K), CLASSES, rotation=30); ax.set_yticks(range(K), CLASSES)
    ax.set_xlabel("predicted"); ax.set_ylabel("expert label")
    ax.set_title(f"{NAMES[sel]}: share of each true class", loc="left", fontsize=10, color=INK)
    paths["confusion_matrix"] = _save(fig, out, "confusion_matrix", SOURCE, root)

    # 4. mIoU by agreement level, with validation for reference
    fig, ax = plt.subplots(figsize=(7, 3.8))
    fig.patch.set_facecolor(BG)
    _style(ax)
    cols = ["validation\n(crowd labels)"] + [f"test {a}" for a in AGREEMENT]
    for j, m in enumerate(models):
        vals = [r["validation_miou"][m]] + [r["test"][a][m]["miou"] for a in AGREEMENT]
        ax.plot(range(len(cols)), vals, marker="o", color=shades[j % 3], label=NAMES[m], lw=2)
        ax.text(len(cols) - 0.9, vals[-1], f"{vals[-1]:.2f}", va="center", fontsize=8, color=MUTED)
    ax.set_xticks(range(len(cols)), cols)
    ax.grid(axis="y", color=GRID); ax.grid(axis="x", visible=False)
    ax.set_ylim(0, 1); ax.set_xlim(-0.3, len(cols) - 0.4)
    ax.set_ylabel("mIoU")
    ax.legend(frameon=False, fontsize=8, loc="upper left", bbox_to_anchor=(1.0, 1.0))
    ax.set_title("mIoU: crowd-labelled validation vs expert test (stricter agreement to the right)", loc="left", fontsize=10, color=INK)
    paths["miou_by_agreement"] = _save(fig, out, "miou_by_agreement", SOURCE, root)

    # 5. training curves
    fig, ax = plt.subplots(figsize=(6.5, 3.6))
    fig.patch.set_facecolor(BG)
    _style(ax)
    for j, (m, h) in enumerate(r["histories"].items()):
        ax.plot([e["epoch"] for e in h], [e["val_miou"] for e in h], marker="o", color=shades[(j + 1) % 3], label=NAMES[m], lw=2)
    ax.grid(axis="y", color=GRID)
    ax.xaxis.set_major_locator(matplotlib.ticker.MaxNLocator(integer=True))
    ax.set_xlabel(f"epoch ({r['config']['samples_per_epoch']} random training images each)")
    ax.set_ylabel("validation mIoU")
    ax.legend(frameon=False, fontsize=8)
    ax.set_title("Validation mIoU during training", loc="left", color=INK)
    paths["training_curves"] = _save(fig, out, "training_curves", SOURCE, root)
    return paths
