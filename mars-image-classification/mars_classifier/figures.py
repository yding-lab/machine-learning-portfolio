"""Report figures."""

from __future__ import annotations

import textwrap
from pathlib import Path

import numpy as np
from PIL import Image

BLUE, ORANGE, AQUA = "#2a78d6", "#eb6834", "#1baf7a"
INK, INK2, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
NICE = {"majority": "Majority class", "small_cnn": "Small CNN (scratch)", "linear_probe": "ResNet-18 linear probe",
        "finetuned_resnet18": "ResNet-18 fine-tuned"}
CREDIT = ("Images: NASA/JPL-Caltech/MSSS, MSL labeled data set (Stanboli & Wagstaff 2017, doi:10.5281/zenodo.1049137), "
          "CC BY-SA 4.0. This figure is shared under the same license.")


def _style(ax, title, xlabel="", ylabel="", grid="x"):
    ax.set_facecolor(SURFACE)
    ax.set_title(title, color=INK, fontsize=11, loc="left")
    ax.set_xlabel(xlabel, color=INK2, fontsize=9)
    ax.set_ylabel(ylabel, color=INK2, fontsize=9)
    ax.tick_params(colors=INK2, labelsize=8)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(GRID)
    if grid:
        ax.grid(True, axis=grid, color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)


def save_figures(out: Path, r: dict, splits, root: Path) -> dict:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out.mkdir(parents=True, exist_ok=True)
    d = r["data"]
    caption = (f"Data: NASA/JPL MSL (Curiosity) labeled images via data.gov. Train sols {d['sols']['train'][0]}-{d['sols']['train'][1]} "
               f"({d['n']['train']:,} images), test sols {d['sols']['test'][0]}-{d['sols']['test'][1]} ({d['n']['test']:,}). "
               "Generated by python -m mars_classifier.train")
    paths = {}

    def finish(fig, name, text=caption):
        width = int(fig.get_size_inches()[0] * 17)
        t = "\n".join(textwrap.wrap(text, width))
        fig.text(0.01, 0.01, t, fontsize=7, color=INK2, ha="left", va="bottom")
        fig.tight_layout(rect=(0, 0.03 + 0.03 * t.count("\n") + 0.02, 1, 1))
        p = out / f"{name}.png"
        fig.savefig(p, dpi=130, facecolor=SURFACE)
        plt.close(fig)
        try:
            paths[name] = str(p.resolve().relative_to(root))
        except ValueError:
            paths[name] = str(p)

    # 1. sample images: one per class for 12 classes, from the training split
    by_class = {}
    for it in splits["train"]:
        by_class.setdefault(it.label, it)
    picks = list(by_class.values())[:12]
    names = dict(zip(sorted({i.label for i in splits["train"]}), d["classes"]))
    fig, axes = plt.subplots(2, 6, figsize=(10, 4.2), facecolor=SURFACE)
    for ax, it in zip(axes.ravel(), picks):
        with Image.open(it.path) as im:
            ax.imshow(im.convert("RGB"))
        ax.set_title(names[it.label], fontsize=8, color=INK)
        ax.axis("off")
    for ax in axes.ravel()[len(picks):]:
        ax.axis("off")
    finish(fig, "samples", CREDIT)

    # 2. model comparison: validation vs test macro-F1
    models = [m for m in NICE if m in r["test"]]
    x = np.arange(len(models))
    fig, ax = plt.subplots(figsize=(6.6, 3.8), facecolor=SURFACE)
    ax.bar(x - 0.2, [r["validation"][m]["macro_f1"] for m in models], 0.38, color=ORANGE, label="validation (sols 182-564)")
    ax.bar(x + 0.2, [r["test"][m]["macro_f1"] for m in models], 0.38, color=BLUE, label="test (sols 565-1060)")
    for i, m in enumerate(models):
        ax.text(i + 0.2, r["test"][m]["macro_f1"] + 0.01, f"{r['test'][m]['macro_f1']:.2f}", ha="center", fontsize=8, color=INK2)
    ax.set_xticks(x, [NICE[m] for m in models], fontsize=8)
    _style(ax, "Macro-F1 by model", "", "macro-F1 (classes present in the split)", grid="y")
    ax.legend(fontsize=8, frameon=False)
    finish(fig, "model_comparison")

    # 3. per-class F1 on test, with support
    rows = sorted(r["per_class_test"], key=lambda c: c["f1"])
    fig, ax = plt.subplots(figsize=(7, 0.32 * len(rows) + 1.5), facecolor=SURFACE)
    ax.barh(range(len(rows)), [c["f1"] for c in rows], color=BLUE, height=0.65)
    for i, c in enumerate(rows):
        ax.text(c["f1"] + 0.01, i, f"{c['f1']:.2f} (n={c['support']}, train n={d['train_counts'][c['class']]})", va="center", fontsize=7, color=INK2)
    ax.set_yticks(range(len(rows)), [c["class"] for c in rows], fontsize=8)
    ax.set_xlim(0, 1.35)
    _style(ax, f"Per-class F1, test split ({NICE[r['selected']['model']]})", "F1")
    finish(fig, "per_class_f1")

    # 4. confusion matrix (row-normalised, classes present in test)
    cm = np.array(r["confusion_test"]["matrix"], dtype=float)
    pres = r["confusion_test"]["rows_present"]
    sub = cm[np.ix_(pres, pres)]
    norm = sub / np.maximum(cm[pres].sum(1, keepdims=True), 1)
    fig, ax = plt.subplots(figsize=(8.5, 7.6), facecolor=SURFACE)
    ax.imshow(norm, cmap=matplotlib.colors.LinearSegmentedColormap.from_list("b", ["#fcfcfb", "#256abf"]), vmin=0, vmax=1)
    lab = [d["classes"][i] for i in pres]
    ax.set_xticks(range(len(pres)), lab, rotation=90, fontsize=7)
    ax.set_yticks(range(len(pres)), lab, fontsize=7)
    for (i, j), v in np.ndenumerate(norm):
        if v >= 0.1:
            ax.text(j, i, f"{v:.1f}", ha="center", va="center", fontsize=6, color="white" if v > 0.5 else INK)
    ax.set_xlabel("predicted", color=INK2, fontsize=9)
    ax.set_ylabel("true", color=INK2, fontsize=9)
    ax.set_title("Test confusion matrix (share of each true class)", loc="left", fontsize=11, color=INK)
    finish(fig, "confusion_matrix")

    # 5. by instrument
    g = r["by_instrument_test"]
    fig, ax = plt.subplots(figsize=(6, 3.4), facecolor=SURFACE)
    ax.barh(range(len(g)), [x["accuracy"] for x in g], color=BLUE, height=0.6)
    for i, x in enumerate(g):
        ax.text(x["accuracy"] + 0.01, i, f"{x['accuracy']:.2f} accuracy, macro-F1 {x['macro_f1']:.2f} (n={x['n']})", va="center", fontsize=7, color=INK2)
    ax.set_yticks(range(len(g)), [x["group"] for x in g])
    ax.set_xlim(0, 1.5)
    _style(ax, "Test results by camera", "accuracy")
    finish(fig, "by_instrument")
    return paths
