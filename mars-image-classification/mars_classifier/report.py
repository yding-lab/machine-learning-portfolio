"""Markdown report from results.json."""

from __future__ import annotations

from .figures import NICE


def markdown(r: dict) -> str:
    d, sel = r["data"], r["selected"]["model"]
    ci = r["test_intervals"]["selected"]
    lines = [
        "# Results: mars-image-classification", "",
        f"Generated by `python -m mars_classifier.train` at {r['generated_utc']} (Python {r['environment']['python']}, "
        f"PyTorch {r['environment']['torch']}, torchvision {r['environment']['torchvision']}, weights {r['environment']['pretrained_weights']}).", "",
        "## Data", "",
        f"- Images: train {d['n']['train']:,} (sols {d['sols']['train'][0]}-{d['sols']['train'][1]}), validation {d['n']['val']:,} "
        f"(sols {d['sols']['val'][0]}-{d['sols']['val'][1]}), test {d['n']['test']:,} (sols {d['sols']['test'][0]}-{d['sols']['test'][1]}).",
        f"- {len(d['classes'])} classes seen in training. Images of classes never seen in training: {d['dropped_unseen_class']}.",
        f"- Camera mix: {d['instrument_mix']}.", "",
        "## Model search (validation macro-F1)", "",
        "| Model | Settings | Validation macro-F1 |", "|---|---|---|",
        *[f"| {NICE[s['model']]} | {s['params']} | {s['val_macro_f1']:.3f} |" for s in r["search"]], "",
        f"Selected: **{NICE[sel]}** {r['selected']['params']}.", "",
        "## Test (scored once)", "",
        "| Model | Accuracy | Macro-F1 | Balanced accuracy | Top-3 accuracy |", "|---|---|---|---|---|",
        *[f"| {NICE[k]} | {v['accuracy']:.3f} | {v['macro_f1']:.3f} | {v['balanced_accuracy']:.3f} | "
          f"{('%.3f' % v['top3_accuracy']) if 'top3_accuracy' in v else '—'} |" for k, v in r["test"].items()], "",
        f"Selected model, 95% bootstrap intervals ({r['config']['n_bootstrap']} resamples): accuracy "
        f"{ci['accuracy'][0]:.3f}–{ci['accuracy'][1]:.3f}, macro-F1 {ci['macro_f1'][0]:.3f}–{ci['macro_f1'][1]:.3f}, "
        f"balanced accuracy {ci['balanced_accuracy'][0]:.3f}–{ci['balanced_accuracy'][1]:.3f}.", "",
        "Paired macro-F1 difference, selected minus each other model:", "",
        *[f"- vs {NICE[k]}: {v['mean']:+.3f} ({v['ci95'][0]:+.3f} to {v['ci95'][1]:+.3f})" for k, v in r["test_intervals"]["macro_f1_difference_vs"].items()], "",
        "## Per class (test, selected model)", "",
        "| Class | Train n | Test n | Precision | Recall | F1 |", "|---|---|---|---|---|---|",
        *[f"| {c['class']} | {d['train_counts'][c['class']]} | {c['support']} | {c['precision']:.2f} | {c['recall']:.2f} | {c['f1']:.2f} |"
          for c in sorted(r["per_class_test"], key=lambda c: -c["support"])], "",
        "## By camera (test, selected model)", "",
        "| Camera | n | Accuracy | Macro-F1 |", "|---|---|---|---|",
        *[f"| {g['group']} | {g['n']} | {g['accuracy']:.3f} | {g['macro_f1']:.3f} |" for g in r["by_instrument_test"]], "",
        "Figures: " + ", ".join(f"`{v}`" for v in r["figures"].values()), "",
    ]
    return "\n".join(lines)
