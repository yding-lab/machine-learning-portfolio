"""Report figures (matplotlib, PNG)."""

from __future__ import annotations

import textwrap
from pathlib import Path

import numpy as np

BLUE, ORANGE, AQUA, YELLOW = "#2a78d6", "#eb6834", "#1baf7a", "#eda100"  # validated categorical slots 1-4
INK, INK2, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
MODEL_STYLE = {"logistic_regression": (ORANGE, "--", "Logistic regression"),
               "gradient_boosting": (AQUA, "-.", "Gradient boosting"),
               "pytorch_mlp": (BLUE, "-", "PyTorch MLP")}


def _style(ax, title, xlabel, ylabel, grid="both"):
    ax.set_facecolor(SURFACE)
    ax.set_title(title, color=INK, fontsize=11, loc="left")
    ax.set_xlabel(xlabel, color=INK2, fontsize=9)
    ax.set_ylabel(ylabel, color=INK2, fontsize=9)
    ax.tick_params(colors=INK2, labelsize=8)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.grid(True, axis=grid, color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)


def save_figures(out_dir: Path, r: dict, y, probs: dict, root: Path) -> dict:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from sklearn.metrics import precision_recall_curve

    out_dir.mkdir(parents=True, exist_ok=True)
    d = r["data"]
    caption = (f"Data: HMDA public loan data (CFPB/FFIEC, data.gov), New York home-purchase applications. "
               f"Train/validation = {d['n_train'] + d['n_validation']:,} decided in 2023, test = {d['n_test']:,} decided in 2024. "
               "Generated by python -m mortgage_approval.train")
    paths = {}

    def finish(fig, name):
        width = int(fig.get_size_inches()[0] * 17)
        text = "\n".join(textwrap.wrap(caption, width))
        fig.text(0.01, 0.01, text, fontsize=7, color=INK2, ha="left", va="bottom")
        fig.tight_layout(rect=(0, 0.03 + 0.03 * text.count("\n") + 0.02, 1, 1))
        p = out_dir / f"{name}.png"
        fig.savefig(p, dpi=150, facecolor=SURFACE)
        plt.close(fig)
        try:
            paths[name] = str(p.resolve().relative_to(root))
        except ValueError:
            paths[name] = str(p)

    # 1. precision-recall curves, test
    fig, ax = plt.subplots(figsize=(6.4, 4.4), facecolor=SURFACE)
    for m, (color, ls, label) in MODEL_STYLE.items():
        if m in probs:
            pr, rc, _ = precision_recall_curve(y, probs[m])
            ax.plot(rc, pr, color=color, ls=ls, lw=2, label=f"{label} (AP {r['test'][m]['average_precision']:.3f})")
    ax.axhline(np.mean(y), color=INK2, lw=1, ls=":")
    ax.text(0.01, np.mean(y) + 0.015, f"no-skill baseline ({np.mean(y):.3f})", fontsize=7, color=INK2, ha="left")
    _style(ax, "Finding denials: precision vs recall, 2024 test", "recall (share of denials flagged)", "precision")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.legend(fontsize=8, frameon=False, loc="upper right")
    finish(fig, "pr_curves")

    # 2. calibration of the selected model
    fig, ax = plt.subplots(figsize=(4.8, 4.4), facecolor=SURFACE)
    ax.plot([0, 1], [0, 1], color=GRID, lw=1, ls="--")
    for key, color, label, marker in (("validation", ORANGE, "2023 validation", "s"), ("test", BLUE, "2024 test", "o")):
        b = r["calibration"][key]
        ax.plot([x["mean_predicted"] for x in b], [x["observed"] for x in b], color=color, lw=2, marker=marker, ms=5, label=label)
    hi = max(max(x["mean_predicted"], x["observed"]) for k in ("validation", "test") for x in r["calibration"][k])
    ax.set_xlim(0, min(1, hi * 1.1))
    ax.set_ylim(0, min(1, hi * 1.1))
    _style(ax, "Calibration of P(denied), 10 bins", "predicted probability", "observed denial rate")
    ax.legend(fontsize=8, frameon=False, loc="upper left")
    finish(fig, "calibration")

    # 3. fairness by race: recall and false-positive rate with 95% intervals
    rows = [g for g in r["fairness"]["derived_race"]]
    fig, axes = plt.subplots(1, 2, figsize=(9.2, 4.2), facecolor=SURFACE, sharey=True)
    yy = np.arange(len(rows))
    for ax, key, color, title in ((axes[0], "recall", BLUE, "Denials flagged (recall)"),
                                  (axes[1], "fpr", ORANGE, "Approvals wrongly flagged (FPR)")):
        vals = [g[key] for g in rows]
        lo = [g[key] - g[f"{key}_ci95"][0] for g in rows]
        hi_ = [g[f"{key}_ci95"][1] - g[key] for g in rows]
        ax.errorbar(vals, yy, xerr=[lo, hi_], fmt="o", color=color, ecolor=color, elinewidth=1.5, capsize=3, ms=6)
        _style(ax, title, "rate (95% Wilson interval)", "", grid="x")
        ax.set_xlim(0, 1 if key == "recall" else max(0.3, max(vals) * 1.6))
    axes[0].set_yticks(yy, [f"{g['group']} (n={g['n']:,})" for g in rows])
    axes[0].invert_yaxis()
    finish(fig, "fairness_race")

    # 4. permutation importance (top 12)
    imp = r["permutation_importance_validation"][:12][::-1]
    fig, ax = plt.subplots(figsize=(6.4, 4.4), facecolor=SURFACE)
    ax.barh(range(len(imp)), [x["ap_drop"] for x in imp], color=BLUE, height=0.6)
    ax.set_yticks(range(len(imp)), [x["feature"] for x in imp])
    _style(ax, "What the selected model relies on (validation)", "drop in average precision when shuffled", "", grid="x")
    finish(fig, "importance")

    # 5. error analysis by DTI band
    rows = r["error_analysis"]["dti"]
    order = ["<30", "30-36", "36-43", "43-50", "50+"]
    rows = sorted([g for g in rows if g["group"] in order], key=lambda g: order.index(g["group"]))
    x = np.arange(len(rows))
    fig, ax = plt.subplots(figsize=(6.4, 4.2), facecolor=SURFACE)
    ax.bar(x - 0.2, [g["denial_rate"] for g in rows], 0.38, color=INK2, alpha=0.35, label="actual denial rate")
    ax.bar(x + 0.2, [g["flag_rate"] for g in rows], 0.38, color=BLUE, label="flagged by model")
    for i, g in enumerate(rows):
        ax.text(i, max(g["denial_rate"], g["flag_rate"]) + 0.01, f"recall {g['recall']:.2f}", ha="center", fontsize=7, color=INK2)
    ax.set_xticks(x, [f"DTI {g['group']}%\n(n={g['n']:,})" for g in rows])
    _style(ax, "Denials and model flags by debt-to-income band, 2024 test", "", "share of applications", grid="y")
    ax.legend(fontsize=8, frameon=False, loc="upper left")
    finish(fig, "error_by_dti")
    return paths
