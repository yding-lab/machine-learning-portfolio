"""Markdown report generated from results.json."""

from __future__ import annotations

NAMES = {"prior": "Prior (denial rate for everyone)", "logistic_regression": "Logistic regression",
         "gradient_boosting": "Gradient boosting", "pytorch_mlp": "PyTorch MLP"}


def _ci(v):
    return f"{v[0]:.3f} – {v[1]:.3f}"


def markdown(r: dict) -> str:
    d, sel = r["data"], r["selected"]
    m = sel["model"]
    t = r["test"][m]
    ci = r["test_intervals"]["selected"]
    lines = [
        "# Results: mortgage-approval",
        "",
        f"Generated by `python -m mortgage_approval.train` at {r['generated_utc']} (Python {r['environment']['python']}, "
        f"scikit-learn {r['environment']['scikit_learn']}, PyTorch {r['environment']['torch']}). Snapshot sha256 "
        f"{str(d['snapshot_sha256'])[:12]}…, retrieved {str(d['retrieved_utc'])[:10]}.",
        "",
        "## Data",
        "",
        f"- Train {d['n_train']:,} and validation {d['n_validation']:,} applications decided in 2023; test {d['n_test']:,} decided in 2024.",
        f"- Denial rate: {d['denial_rate']['train']:.3f} (train), {d['denial_rate']['validation']:.3f} (validation), {d['denial_rate']['test']:.3f} (test).",
        f"- Excluded for missing LTV, property value, loan term or DTI: {d['excluded_incomplete']['train']['excluded']:,} of "
        f"{d['excluded_incomplete']['train']['total']:,} (2023) and {d['excluded_incomplete']['test']['excluded']:,} of "
        f"{d['excluded_incomplete']['test']['total']:,} (2024). Their denial rate was "
        f"{d['excluded_incomplete']['train']['denial_rate_excluded']:.1%} / {d['excluded_incomplete']['test']['denial_rate_excluded']:.1%}.",
        "",
        "## Model search (validation set, average precision)",
        "",
        "| Model | Settings | Validation AP | Validation ROC-AUC |",
        "|---|---|---|---|",
        *[f"| {NAMES[s['model']]} | {s['params'] or '—'}{' (epoch ' + str(s['best_epoch']) + ')' if 'best_epoch' in s else ''} | "
          f"{s['val_average_precision']:.3f} | {s['val_roc_auc']:.3f} |" for s in r["search"]],
        "",
        f"Selected: **{NAMES[m]}** {sel['params']}, threshold {sel['threshold']:.3f} (best F1 on validation).",
        "",
        "## Test (2024, scored once)",
        "",
        "| Model | Average precision | ROC-AUC | Brier | Recall at its threshold | Precision at its threshold |",
        "|---|---|---|---|---|---|",
        *[f"| {NAMES[k]} | {v['average_precision']:.3f} | {v['roc_auc']:.3f} | {v['brier']:.4f} | "
          f"{(f'{v['at_threshold']['recall']:.3f}' if v['at_threshold'] else '—')} | "
          f"{(f'{v['at_threshold']['precision']:.3f}' if v['at_threshold'] else '—')} |" for k, v in r["test"].items()],
        "",
        f"Selected model, 95% bootstrap intervals ({r['config']['n_bootstrap']} resamples of test applications): "
        f"AP {_ci(ci['average_precision'])}, ROC-AUC {_ci(ci['roc_auc'])}, recall {_ci(ci['recall'])}, precision {_ci(ci['precision'])}.",
        "",
        "Paired difference in AP, selected model minus each other model (95% interval):",
        "",
        *[f"- vs {NAMES[k]}: {v['mean']:+.3f} ({v['ci95'][0]:+.3f} to {v['ci95'][1]:+.3f})" for k, v in r["test_intervals"]["ap_difference_vs"].items()],
        "",
        "## Fairness audit (selected model, test, groups with n ≥ 100)",
        "",
    ]
    for attr, rows in r["fairness"].items():
        lines += [f"**{attr}**", "", "| Group | n | Actual denial rate | Flag rate | Recall (95% CI) | False-positive rate (95% CI) |",
                  "|---|---|---|---|---|---|",
                  *[f"| {g['group']} | {g['n']:,} | {g['denial_rate']:.3f} | {g['flag_rate']:.3f} | {g['recall']:.3f} "
                    f"({g['recall_ci95'][0]:.3f}–{g['recall_ci95'][1]:.3f}) | {g['fpr']:.3f} ({g['fpr_ci95'][0]:.3f}–{g['fpr_ci95'][1]:.3f}) |"
                    for g in rows], ""]
    lines += ["## Error analysis (selected model, test)", ""]
    for k, rows in r["error_analysis"].items():
        lines += [f"**{k}**", "", "| Band | n | Actual denial rate | Flag rate | Recall | False-positive rate |", "|---|---|---|---|---|---|",
                  *[f"| {g['group']} | {g['n']:,} | {g['denial_rate']:.3f} | {g['flag_rate']:.3f} | {g['recall']:.3f} | {g['fpr']:.3f} |" for g in rows], ""]
